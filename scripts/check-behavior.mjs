import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import vm from 'node:vm';
const root = new URL('../',import.meta.url);
const scope = {URL};scope.window=scope;
vm.createContext(scope);
for(const file of ['config.js','routing.js','analytics.js']) vm.runInContext(readFileSync(new URL(file,root),'utf8'),scope);
const routing=scope.ThriveRouting;
assert.equal(routing.platformFrom('Mozilla iPhone'), 'apple');
assert.equal(routing.platformFrom('Mozilla Android'), 'google');
assert.equal(routing.platformFrom('Mozilla Macintosh','MacIntel',5), 'apple');
assert.equal(routing.platformFrom('Mozilla Macintosh','MacIntel',0), null);
assert.equal(routing.platformFrom('Mozilla Windows'), null);
assert.equal(routing.storeURL('apple',null),null);
assert.equal(routing.storeURL('google','https://example.com/app'),null);
assert.equal(routing.storeURL('apple','https://apps.apple.com.evil.example/app'),null);
assert.equal(routing.storeURL('apple','https://bad:secret@apps.apple.com/app'),null);
assert.equal(routing.storeURL('google','javascript:alert(1)'),null);
assert.equal(routing.storeURL('apple','http://apps.apple.com/app'),null);
assert.equal(routing.storeURL('apple','https://apps.apple.com/app/id123'),'https://apps.apple.com/app/id123');
assert.equal(routing.storeURL('google','https://play.google.com/store/apps/details?id=test'),'https://play.google.com/store/apps/details?id=test');
let transmitted=0;scope.THRIVE_CONFIG.analytics.adapter={send(){transmitted++;}};
assert.equal(scope.ThriveAnalytics.track('primary_cta_click',{location:'hero',symptoms:'private',email:'private'}),true);
assert.equal(transmitted,0);
const event=scope.ThriveAnalytics.diagnostics()[0];
assert.equal('symptoms' in event.properties,false);assert.equal('email' in event.properties,false);
for(const name of ['app_install','trial_started','trial_converted_to_paid']) assert.equal(scope.ThriveAnalytics.track(name),false);
scope.THRIVE_CONFIG.analytics.enabled=true;
scope.ThriveAnalytics.track('landing_page_view');assert.equal(transmitted,0);
scope.THRIVE_CONFIG.analytics.consentGranted=true;
scope.ThriveAnalytics.track('store_redirect',{platform:'apple'});assert.equal(transmitted,1);
assert.equal(scope.THRIVE_CONFIG.testimonials.every(item=>item.verified===false),true);
console.log('Passed routing, consent, sensitive-property and conversion-semantics assertions.');
